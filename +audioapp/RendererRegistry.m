classdef RendererRegistry < handle
    % RendererRegistry  Central catalog of all renderer descriptors.
    %
    % This singleton replaces:
    %   - sound_scene_renderer.make_renderer_for()  switch-case
    %   - AppContext.rendererDictionary()
    %   - ModeMap.registry()  (UI ↔ internal name mapping)
    %   - Rules.isutilible()  (geometry compatibility)
    %   - Rules.preferredGeometryForRenderer()
    %   - Rules.preferredRendererForGeometry()
    %   - Rules.canonR()
    %   - RendererPanelFactory.create()
    %   - RendererTab popup list
    %
    % === Használat ===
    %
    %   reg = RendererRegistry.instance();    % singleton
    %
    %   % Renderer létrehozása (make_renderer_for helyett):
    %   r = reg.create('wfs', vs, SSD, ls, rec, setup);
    %
    %   % UI panel létrehozása (RendererPanelFactory helyett):
    %   pnl = reg.createPanel('wfs', parent, C);
    %
    %   % Popup lista (RendererTab helyett):
    %   uiNames = reg.uiList();
    %
    %   % Geometria kompatibilitás (Rules.isutilible helyett):
    %   tf = reg.supportsGeometry('wfs', 'linear');
    %
    %   % Név feloldás (ModeMap + rendererDictionary helyett):
    %   id = reg.resolveId('NFC_HOA');           % → 'nfc_hoa'
    %   ui = reg.toUI('nfc_hoa');                % → 'NFC_HOA'
    %
    %   % Default setup mezők:
    %   ds = reg.defaultSetup('wfs');

    properties (Access = private)
        descriptors   containers.Map   % id → RendererDescriptor
    end

    methods (Access = private)
        function obj = RendererRegistry()
            obj.descriptors = containers.Map();
            obj.registerAll();
        end
    end

    % ─── Singleton ───
    methods (Static)
        function reg = instance()
            persistent inst
            if isempty(inst) || ~isvalid(inst)
                inst = audioapp.RendererRegistry();
            end
            reg = inst;
        end
    end

    % ─── Public API ───
    methods
        function register(obj, desc)
            % register(audioapp.RendererDescriptor)
            validateattributes(desc, {'audioapp.RendererDescriptor'}, {'scalar'});
            obj.descriptors(desc.id) = desc;
        end

        function d = get(obj, idOrName)
            id = obj.resolveId(idOrName);
            if obj.descriptors.isKey(id)
                d = obj.descriptors(id);
            else
                warning('RendererRegistry:unknown', ...
                    'Unknown renderer "%s", falling back to direct_playback.', idOrName);
                d = obj.descriptors('direct_playback');
            end
        end

        % --- Renderer creation (replaces make_renderer_for) ---
        function r = create(obj, idOrName, vs, SSD, loudspeakers, receiver, setup)
            d = obj.get(idOrName);
            r = d.createRenderer(vs, SSD, loudspeakers, receiver, setup);
        end

        % --- Panel creation (replaces RendererPanelFactory.create) ---
        function pnl = createPanel(obj, idOrName, parent, C)
            d = obj.get(idOrName);
            pnl = d.createPanel(parent, C);
        end

        % --- Name resolution (replaces ModeMap + rendererDictionary + canonR) ---
        function id = resolveId(obj, nameAny)
            % Accepts any form: UI name, internal id, synonym → returns internal id
            if isempty(nameAny), id = 'wfs'; return; end
            key = obj.norm(nameAny);

            % 1. Direct id match
            keys = obj.descriptors.keys;
            for k = 1:numel(keys)
                if strcmp(key, obj.norm(keys{k}))
                    id = keys{k}; return;
                end
            end

            % 2. UI name match
            vals = obj.descriptors.values;
            for k = 1:numel(vals)
                d = vals{k};
                if strcmp(key, obj.norm(d.uiName))
                    id = d.id; return;
                end
            end

            % 3. Synonym match
            for k = 1:numel(vals)
                d = vals{k};
                for j = 1:numel(d.synonyms)
                    if strcmp(key, obj.norm(d.synonyms{j}))
                        id = d.id; return;
                    end
                end
            end

            % 4. Fallback
            id = 'wfs';
        end

        function ui = toUI(obj, idOrName)
            d = obj.get(idOrName);
            ui = d.uiName;
        end

        % --- UI list (replaces RendererTab hardcoded modes) ---
        function list = uiList(obj)
            vals = obj.descriptors.values;
            descs = [vals{:}];
            descs = descs(~[descs.hidden]);
            [~, ix] = sort([descs.sortOrder]);
            descs = descs(ix);
            list = {descs.uiName};
        end

        % --- Geometry queries (replaces Rules.isutilible + preferred*) ---
        function tf = supportsGeometry(obj, idOrName, geom)
            geom = audioapp.RendererRegistry.normGeom(geom);
            d = obj.get(idOrName);
            tf = d.supportsGeometry(geom);
        end

        function geom = preferredGeometry(obj, idOrName)
            d = obj.get(idOrName);
            geom = d.prefGeometry;
        end

        function id = preferredRendererForGeometry(obj, geom)
            % Visszaadja az első (sortOrder szerint) renderert,
            % ami támogatja az adott geometriát.
            geom = audioapp.RendererRegistry.normGeom(geom);
            vals = obj.descriptors.values;
            descs = [vals{:}];
            descs = descs(~[descs.hidden]);
            [~, ix] = sort([descs.sortOrder]);
            descs = descs(ix);
            for k = 1:numel(descs)
                if descs(k).supportsGeometry(geom)
                    id = descs(k).id; return;
                end
            end
            id = 'direct_playback';
        end

        % --- Default setup (replaces scattered defaults) ---
        function s = defaultSetup(obj, idOrName)
            d = obj.get(idOrName);
            s = d.defaultSetup;
        end

        % --- Resolve on change (replaces Rules.resolveOnRendererChange) ---
        function [modeOut, geomOut, changed] = resolveOnRendererChange(obj, rendererIn, geomCur)
            modeOut = obj.resolveId(rendererIn);
            geomOut = audioapp.RendererRegistry.normGeom(geomCur);
            d = obj.get(modeOut);
            if d.supportsGeometry(geomOut)
                changed = false;
            else
                geomOut = d.prefGeometry;
                changed = true;
            end
        end

        function [modeOut, geomOut, changed] = resolveOnGeometryChange(obj, geomIn, modeCur)
            geomOut = audioapp.RendererRegistry.normGeom(geomIn);
            modeOut = obj.resolveId(modeCur);
            d = obj.get(modeOut);
            supported = d.supportsGeometry(geomOut);
            if supported
                changed = false;
            else
                modeOut = obj.preferredRendererForGeometry(geomOut);
                changed = true;
            end
        end
    end

