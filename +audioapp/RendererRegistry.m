    methods (Static, Access = private)
        function s = norm(s0)
            if isstring(s0), s0 = char(s0); end
            if ~ischar(s0), s0 = ''; end
            s = lower(strrep(strrep(strtrim(s0),'-','_'),' ','_'));
            s = regexprep(s,'__+','_');
        end
    end

    methods (Static)
        function g = normGeom(g)
            %NORMGEOM  Normalize geometry names to canonical form.
            %   '5.0 (circular)' → '5.0',  'Circular' → 'circular', etc.
            if isstring(g), g = char(g); end
            if ~ischar(g), g = ''; end
            g = lower(strtrim(g));
            switch g
                case {'5.0 (circular)', '5_0', '5.0 (circular) '}, g = '5.0';
                case {'5.1 (circular)'}, g = '5.1';
                case {'atmos 5.1.4'}, g = '5.1.4';
                case {'atmos 7.1.4'}, g = '7.1.4';
                case {'soundbar (16 ch)', 'soundbar 16'}, g = 'soundbar';
                case {'genius array'}, g = 'genius_array';
            end
        end
